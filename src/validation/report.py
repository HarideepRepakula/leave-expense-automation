"""Validation report files (docs/07 section 11): data/validation/validation_report.{csv,json,md} and
validation_findings.csv. Deterministic content (no timestamps), so the files take part in the reproducibility
check (M13). Every number in the Markdown comes from the computed results; nothing is typed by hand.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

import yaml

from src.validation.checks import CheckResult, summary_metrics, validate
from src.validation.reader import read_raw


def weekend_days(config_dir: Path) -> dict[str, list[int]]:
    return yaml.safe_load((config_dir / "calendar.yaml").read_text(encoding="utf-8"))["weekend_days"]


def validate_folder(raw_dir: Path, config_dir: Path) -> tuple[list[CheckResult], dict]:
    results = validate(read_raw(raw_dir), weekend_days(config_dir))
    return results, summary_metrics(results)


DETECTION_COLUMNS = ["record_type", "record_id", "exception_code", "detected_by", "detail"]


def write_detections(detections: list, folder: Path) -> Path:
    """data/validation/detections.csv (docs/08 section 1): one row per (record, code, detector). The rules live in
    src/services (DEC-P4-07); this only writes their output, sorted, so it takes part in the M13 check."""
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / "detections.csv"
    rows = sorted(({c: getattr(d, c) for c in DETECTION_COLUMNS} for d in detections),
                  key=lambda r: tuple(r[c] for c in DETECTION_COLUMNS))
    with path.open("w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=DETECTION_COLUMNS, lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    return path


def write_report(results: list[CheckResult], metrics: dict, folder: Path) -> list[Path]:
    folder.mkdir(parents=True, exist_ok=True)
    summary = [{"check_id": r.check_id, "check_name": r.name, "metric": r.metric, "subjects": r.subjects,
                "violations": r.violations, "status": r.status} for r in results]
    findings = sorted(({"check_id": f.check_id, "table_name": f.table_name, "record_id": f.record_id,
                        "detail": f.detail} for r in results for f in r.findings),
                      key=lambda f: (f["check_id"], f["table_name"], f["record_id"], f["detail"]))
    paths = {"csv": folder / "validation_report.csv", "findings": folder / "validation_findings.csv",
             "json": folder / "validation_report.json", "md": folder / "validation_report.md"}
    for path, rows, cols in ((paths["csv"], summary, list(summary[0])),
                             (paths["findings"], findings, ["check_id", "table_name", "record_id", "detail"])):
        with path.open("w", encoding="utf-8", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=cols, lineterminator="\n")
            w.writeheader()
            w.writerows(rows)
    paths["json"].write_text(json.dumps({"checks": summary, "metrics": metrics, "findings": findings},
                                        sort_keys=True, indent=2) + "\n", encoding="utf-8", newline="\n")
    lines = ["# Validation report", "", "Generated by src.validation from the exported files (docs/07 section 11).", "",
             "| Metric | Name | Numerator | Denominator | Value |", "|---|---|---|---|---|"]
    lines += [f"| {k} | {m['name']} | {m['numerator']} | {m['denominator']} | {m['value']} |" for k, m in metrics.items()]
    lines += ["", "| Check | Description | Metric | Subjects | Violations | Status |", "|---|---|---|---|---|---|"]
    lines += [f"| {s['check_id']} | {s['check_name']} | {s['metric']} | {s['subjects']} | {s['violations']} | "
              f"{s['status']} |" for s in summary]
    lines += ["", f"Findings: {len(findings)} (listed in validation_findings.csv).", ""]
    paths["md"].write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return list(paths.values())
